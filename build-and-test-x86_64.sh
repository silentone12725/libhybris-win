#!/usr/bin/env bash
# Build the libhybris core loader (Q linker + hooks) for x86-64 glibc.
# If HYBRIS_ROOTFS is supplied, also run a dlopen smoke test against a real
# Android x86-64 rootfs; otherwise stop after the reproducible build.
set -euo pipefail

ROOT="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
REPO="$ROOT/hybris"
Q="$REPO/common/q"
COMMON="$REPO/common"
INC="$REPO/include"
HYBRIS_ROOTFS="${HYBRIS_ROOTFS:-}"
HYBRIS_LINKER_DIR="${HYBRIS_LINKER_DIR:-}"
BUILD="/tmp/hybris-x86_64-build"

# MSYS2 rewrites command-line arguments that look like POSIX paths before
# passing them to native Windows programs.  The default ELF library path is a
# C string passed through -D, not a filesystem argument; rewriting it turns
# /odm/lib64 into a malformed preprocessor escape.  Exclude only this define
# from MSYS2 argument conversion while leaving normal compiler paths intact.
case "$(uname -s 2>/dev/null || true)" in
    MINGW*|MSYS*|CYGWIN*)
        if [[ -n "${MSYS2_ARG_CONV_EXCL:-}" ]]; then
            export MSYS2_ARG_CONV_EXCL="${MSYS2_ARG_CONV_EXCL};-DDEFAULT_HYBRIS_LD_LIBRARY_PATH=*"
        else
            export MSYS2_ARG_CONV_EXCL="-DDEFAULT_HYBRIS_LD_LIBRARY_PATH=*"
        fi
        ;;
esac

rm -rf "$BUILD" && mkdir -p "$BUILD"

BIONIC_LIBC="$Q/bionic/libc"
BIONIC_INC="$BIONIC_LIBC/include"
BIONIC_PRIV="$BIONIC_LIBC"

# Stub headers not in the repo
mkdir -p "$BUILD/stub/android-base" "$BUILD/stub/debuggerd"
cat > "$BUILD/stub/android-config.h" << 'EOF'
#pragma once
#define ANDROID_VERSION_MAJOR 10
#define ANDROID_VERSION_MINOR 0
#define ANDROID_VERSION_PATCH 0
EOF
cat > "$BUILD/stub/android-version.h" << 'EOF'
#pragma once
#define ANDROID_VERSION_MAJOR 10
EOF
cat > "$BUILD/stub/android-base/macros.h" << 'EOF'
#pragma once
#define DISALLOW_COPY_AND_ASSIGN(T) T(const T&) = delete; T& operator=(const T&) = delete
#define DISALLOW_IMPLICIT_CONSTRUCTORS(T) T() = delete; DISALLOW_COPY_AND_ASSIGN(T)
EOF
# config.h — generated by autoconf; stub the defines hooks.c needs
cat > "$BUILD/stub/config.h" << 'EOF'
#pragma once
#define PACKAGE_VERSION "0.1.0"
#define TRACE_DEBUG 0
EOF

# cutils/native_handle.h — forward-declare only; the real impl is in native_handle.c
mkdir -p "$BUILD/stub/cutils"
cat > "$BUILD/stub/cutils/native_handle.h" << 'EOF'
#pragma once
#include <stdint.h>
typedef struct native_handle { int version; int numFds; int numInts; int data[0]; } native_handle_t;
native_handle_t* native_handle_create(int numFds, int numInts);
int native_handle_close(const native_handle_t* h);
int native_handle_delete(native_handle_t* h);
EOF

# debuggerd/handler.h — only used under #ifdef __ANDROID__ so a stub is enough to satisfy the include
cat > "$BUILD/stub/debuggerd/handler.h" << 'EOF'
#pragma once
#include <stddef.h>
typedef struct { void *(*get_abort_message)(void); void (*post_dump)(void); } debuggerd_callbacks_t;
static inline void debuggerd_init(debuggerd_callbacks_t *cb) { (void)cb; }
EOF

LD_LIBRARY_PATH_DEFAULT="/system/lib64:/vendor/lib64:/odm/lib64"

CFLAGS_COMMON=(
    -std=c++17
    -fPIC
    -D__ANDROID__
    -DANDROID
    -D_GNU_SOURCE
    -D_LARGEFILE64_SOURCE
    -DWANT_LINKER_Q
    -DANDROID_SMP=1
    -D_USING_LIBCXX
    -DTRACE_DEBUG=0
    -DNO_RUNTIME_PROPERTY_CACHE
    -DLINKER_PLUGIN_DIR='"/tmp/hybris-linker"'
    # climits added per-file below for C++ only
    "-I$INC"
    "-I$COMMON"
    "-I$Q"
    "-I$BIONIC_INC"
    "-I$BIONIC_PRIV"
    "-I$BUILD/stub"
    -w
    -DDYNAMIC_LINKER
)

# Native MinGW compilers already define _WIN32.  Keep the default path in the
# Windows compatibility header instead of sending a POSIX path-list macro
# through the Windows command-line parser.  The Linux build still receives
# the historical configure-style define.
TARGET_TRIPLE="$(g++ -dumpmachine 2>/dev/null || true)"
if [[ "$TARGET_TRIPLE" != *mingw* && "$TARGET_TRIPLE" != *msys* ]]; then
    CFLAGS_COMMON+=("-DDEFAULT_HYBRIS_LD_LIBRARY_PATH=\"$LD_LIBRARY_PATH_DEFAULT\"")
    LINK_LIBS=(-lpthread -ldl -lrt -lsupc++)
else
    # MinGW-w64 uses LLP64 and does not define __LP64__, but this target still
    # consumes Android's 64-bit ABI headers and must use their 64-bit branch.
    CFLAGS_COMMON+=(-D__LP64__)
    LINK_LIBS=(-lsupc++)
fi

if [[ -z "$HYBRIS_LINKER_DIR" ]]; then
    HYBRIS_LINKER_DIR="/tmp/hybris-linker"
    if [[ "$TARGET_TRIPLE" == *mingw* || "$TARGET_TRIPLE" == *msys* ]] && command -v cygpath >/dev/null 2>&1; then
        HYBRIS_LINKER_DIR="$(cygpath -m /tmp/hybris-linker)"
    fi
fi

compile_src() {
    local src="$1"
    local extra_include="${2:-}"
    # Use md5sum of the path to avoid spaces in filenames
    local hash
    hash=$(echo "$src" | md5sum | cut -c1-8)
    local obj="$BUILD/${hash}_$(basename "$src").o"
    local -a cflags=("${CFLAGS_COMMON[@]}")
    if [[ -n "$extra_include" ]]; then
        cflags+=("-include" "$extra_include")
    fi
    echo "$obj"  # return obj path via stdout; errors go to stderr
    if [[ "$src" == *.c ]]; then
        cflags=("${cflags[@]/-std=c++17/-std=gnu11}")
        gcc -c "${cflags[@]}" -x c "$src" -o "$obj"
    else
        g++ -c "${cflags[@]}" -include climits "$src" -o "$obj"
    fi
}

# ── Step 1: Build q linker plugin (q.so) ──────────────────────────────────
echo "=== Compiling q linker plugin ==="
Q_SRCS=(
    "$Q/hybris_compat.cpp"
    "$Q/bionic/libc/bionic/bionic_call_ifunc_resolver.cpp"
    "$Q/dlfcn.cpp"
    "$Q/linker_allocator.cpp"
    "$Q/linker_block_allocator.cpp"
    "$Q/linker.cpp"
    "$Q/linker_cfi.cpp"
    "$Q/linker_config.cpp"
    "$Q/linker_dlwarning.cpp"
    "$Q/linker_gdb_support.cpp"
    "$Q/linker_globals.cpp"
    "$Q/linker_logger.cpp"
    "$Q/linker_main.cpp"
    "$Q/linker_mapped_file_fragment.cpp"
    "$Q/linker_memory.cpp"
    "$Q/linker_namespaces.cpp"
    "$Q/linker_phdr.cpp"
    "$Q/linker_sdk_versions.cpp"
    "$Q/linker_soinfo.cpp"
    "$Q/linker_tls.cpp"
    "$Q/windows_tls_backend.cpp"
    "$Q/linker_utils.cpp"
    "$Q/rt.cpp"
    "$Q/bionic/libc/bionic/bionic_elf_tls.cpp"
    "$Q/bionic/libc/bionic/bionic_allocator.cpp"
    "$Q/x86_64_relocation.c"
    "$COMMON/abi_thunks.c"
    "$COMMON/strlcpy.c"
    "$COMMON/strlcat.c"
)
if [[ "$TARGET_TRIPLE" == *mingw* || "$TARGET_TRIPLE" == *msys* ]]; then
    Q_SRCS+=("$Q/windows_elf_host.c" "$Q/windows_elf_reader.c")
fi
Q_OBJS=()
for src in "${Q_SRCS[@]}"; do
    echo "  CC $(basename "$src")"
    Q_OBJS+=( "$(compile_src "$src")" )
done

echo ""
echo "=== Linking q.so (linker plugin) ==="
mkdir -p /tmp/hybris-linker
g++ -shared -fPIC -o /tmp/hybris-linker/q.so "${Q_OBJS[@]}" \
    "${LINK_LIBS[@]}"
echo "  -> /tmp/hybris-linker/q.so"
ls -lh /tmp/hybris-linker/q.so

if [[ "$TARGET_TRIPLE" == *mingw* || "$TARGET_TRIPLE" == *msys* ]]; then
    echo ""
    echo "=== Building Android x86-64 runtime fixture ==="
    NDK_ROOT="${ANDROID_NDK_ROOT:-$HOME/android-ndk-r26d-windows/android-ndk-r26d}"
    ANDROID_CLANG="$NDK_ROOT/toolchains/llvm/prebuilt/windows-x86_64/bin/clang.exe"
    if [[ ! -x "$ANDROID_CLANG" ]]; then
        echo "ANDROID_NDK_ROOT must point to an Android NDK with clang.exe" >&2
        exit 2
    fi
    FIXTURE="$BUILD/android-fixture"
    mkdir -p "$FIXTURE"
    "$ANDROID_CLANG" --target=x86_64-linux-android29 --sysroot="$NDK_ROOT/toolchains/llvm/prebuilt/windows-x86_64/sysroot" \
        -fPIC -fno-emulated-tls -shared -nostdlib -Wl,-soname,libhybris_fixture_dep.so \
        "$ROOT/fixtures/windows_q_runtime_dep.c" -o "$FIXTURE/libhybris_fixture_dep.so"
    "$ANDROID_CLANG" --target=x86_64-linux-android29 --sysroot="$NDK_ROOT/toolchains/llvm/prebuilt/windows-x86_64/sysroot" \
        -fPIC -fno-emulated-tls -shared -nostdlib -Wl,-soname,libhybris_fixture.so \
        -Wl,--no-as-needed -L"$FIXTURE" -lhybris_fixture_dep \
        "$ROOT/fixtures/windows_q_runtime.c" -o "$FIXTURE/libhybris_fixture.so"
    echo "  -> $FIXTURE/libhybris_fixture.so"

    echo ""
    echo "=== Building Windows Q runtime host ==="
    g++ -std=c++17 -Wall -Wextra -Werror -D_WIN32 \
        "$ROOT/hybris/tests/windows_q_runtime_smoke.cpp" -o "$BUILD/windows_q_runtime_smoke.exe"
    echo "  -> $BUILD/windows_q_runtime_smoke.exe"
    echo ""
    echo "=== Running Windows Q runtime smoke test ==="
    (cd "$FIXTURE" && \
        HYBRIS_LD_LIBRARY_PATH="C:/msys64/tmp/hybris-x86_64-build/android-fixture" \
        "$BUILD/windows_q_runtime_smoke.exe" \
        "/tmp/hybris-linker/q.so" "libhybris_fixture.so")
    echo ""
    echo "=== Windows Q-linker build complete ==="
fi

# ── Step 2: Build libhybris-core.so (public API + hooks) ──────────────────
echo ""
echo "=== Compiling hybris common (hooks + public API) ==="
COMMON_SRCS=(
    "$COMMON/hooks.c"
    "$COMMON/hooks_shm.c"
    "$COMMON/logging.c"
    "$COMMON/native_handle.c"
    "$COMMON/sysconf.c"
    "$COMMON/dso_handle_counters.cpp"
    "$COMMON/legacy_properties/properties.c"
    "$COMMON/legacy_properties/cache.c"
)
if [[ "$TARGET_TRIPLE" == *mingw* || "$TARGET_TRIPLE" == *msys* ]]; then
    COMMON_SRCS[0]="$COMMON/windows_core_hooks.c"
    COMMON_SRCS[6]="$COMMON/windows_core_properties.c"
    unset 'COMMON_SRCS[7]'
fi
COMMON_OBJS=()
for src in "${COMMON_SRCS[@]}"; do
    echo "  CC $(basename "$src")"
    if [[ "$TARGET_TRIPLE" == *mingw* || "$TARGET_TRIPLE" == *msys* ]]; then
        COMMON_OBJS+=( "$(compile_src "$src" "$COMMON/windows_core_compat.h")" )
    else
        COMMON_OBJS+=( "$(compile_src "$src")" )
    fi
done

echo ""
echo "=== Linking libhybris-core.so ==="
g++ -shared -fPIC -o "$BUILD/libhybris-core.so" "${COMMON_OBJS[@]}" \
    "${LINK_LIBS[@]}"

echo "  -> $BUILD/libhybris-core.so"
ls -lh "$BUILD/libhybris-core.so"

echo ""
echo "=== Building dlopen smoke test ==="
cat > "$BUILD/test_hybris_dlopen.cpp" << 'TESTEOF'
#include <stdio.h>
#include <stdlib.h>
#if defined(_WIN32)
#include "windows_core_compat.h"
#else
#include <dlfcn.h>
#include <unistd.h>
#endif

// hybris public API
extern "C" {
    void *android_dlopen(const char *filename, int flag);
    void *android_dlsym(void *handle, const char *symbol);
    int android_dlclose(void *handle);
    const char *android_dlerror(void);

    // hybris linker init
    void hybris_set_hook_params(const char *linker_dir, const char *ld_path);
}

int main() {
    printf("[test] Setting up hybris linker paths\n");
    fflush(stdout);

    const char *rootfs = getenv("HYBRIS_ROOTFS");
    if (rootfs == nullptr || rootfs[0] == '\0') {
        printf("[SKIP] HYBRIS_ROOTFS is not set; build validation completed\n");
        return 0;
    }

    const char *linker_dir = getenv("HYBRIS_LINKER_DIR");
    if (linker_dir == nullptr || linker_dir[0] == '\0') linker_dir = "/tmp/hybris-linker";
    setenv("HYBRIS_LINKER_DIR", linker_dir, 1);
    setenv("HYBRIS_LD_LIBRARY_PATH", rootfs, 1);

    // Pre-load Android implicit system libs so they appear in the soinfo list.
    // On real Android, libdl.so is always implicitly available; on hybris it must be
    // explicitly loaded first so verneed checks can find it in the global solist.
    const char *preload_libs[] = { "libdl.so", "libc.so", "libm.so", nullptr };
    for (int i = 0; preload_libs[i]; i++) {
        char path[512];
        snprintf(path, sizeof(path), "%s/%s", rootfs, preload_libs[i]);
        if (access(path, R_OK) != 0) {
            printf("[skip] preload %s is absent\n", preload_libs[i]);
            continue;
        }
        void *h = android_dlopen(path, RTLD_NOW | RTLD_GLOBAL);
        printf("[init] preload %s: %s\n", preload_libs[i], h ? "ok" : android_dlerror());
        fflush(stdout);
    }

    char lib_path[512];
    const char *configured_lib = getenv("HYBRIS_SMOKE_LIBRARY");
    if (configured_lib != nullptr && configured_lib[0] != '\0') {
        snprintf(lib_path, sizeof(lib_path), "%s", configured_lib);
    } else {
        snprintf(lib_path, sizeof(lib_path), "%s/libstoreservicescore.so", rootfs);
    }
    printf("[test] Attempting android_dlopen(%s)\n", lib_path);
    fflush(stdout);
    const char *lib = lib_path;
    void *handle = android_dlopen(lib, RTLD_NOW | RTLD_LOCAL);
    if (!handle) {
        printf("[FAIL] android_dlopen failed: %s\n", android_dlerror());
        return 1;
    }
    printf("[OK]   android_dlopen succeeded: handle=%p\n", handle);

    // Resolve a caller-selected symbol, or retain the historical default for
    // the storeservicescore fixture.
    const char *configured_symbol = getenv("HYBRIS_SMOKE_SYMBOL");
    const char *sym = (configured_symbol != nullptr && configured_symbol[0] != '\0')
        ? configured_symbol
        : "_ZN17storeservicescore10DeviceGUID8instanceEv";
    void *fn = android_dlsym(handle, sym);
    if (!fn) {
        printf("[FAIL] android_dlsym(%s): %s\n", sym, android_dlerror());
    } else {
        printf("[OK]   android_dlsym resolved: %s -> %p\n", sym, fn);
    }

    // Try a simpler exported symbol
    const char *sym2 = "JNI_OnLoad";
    void *fn2 = android_dlsym(handle, sym2);
    printf("[INFO] JNI_OnLoad: %s\n", fn2 ? "found" : "not exported (expected)");

    android_dlclose(handle);
    printf("[OK]   android_dlclose done\n");
    return fn ? 0 : 1;
}
TESTEOF

CORE_LINK_ARG="-lhybris-core"
if [[ "$TARGET_TRIPLE" == *mingw* || "$TARGET_TRIPLE" == *msys* ]]; then
    CORE_LINK_ARG="$BUILD/libhybris-core.so"
fi
g++ -std=c++17 \
    "-I$INC" "-I$COMMON" "-I$BUILD/stub" \
    "$BUILD/test_hybris_dlopen.cpp" \
    "-L$BUILD" "$CORE_LINK_ARG" \
    "${LINK_LIBS[@]}" \
    "-Wl,-rpath,$BUILD" \
    -o "$BUILD/test_hybris_dlopen"

echo "  -> $BUILD/test_hybris_dlopen"

if [[ -z "$HYBRIS_ROOTFS" ]]; then
    echo ""
    echo "=== Smoke test skipped ==="
    echo "Set HYBRIS_ROOTFS to an Android x86-64 rootfs to run the dlopen test."
else
    echo ""
    echo "=== Running dlopen smoke test ==="
    mkdir -p /tmp/hybris-linker
    HYBRIS_ROOTFS="$HYBRIS_ROOTFS" \
        HYBRIS_LD_LIBRARY_PATH="$HYBRIS_ROOTFS" \
        HYBRIS_LINKER_DIR="$HYBRIS_LINKER_DIR" \
        "$BUILD/test_hybris_dlopen"
fi
